// Helper to generate next sequential booking number starting from SIC2601
export const getNextBookingNumber = (existingDuties: Duty[]): string => {
  let highestNum = 2600;
  existingDuties.forEach(d => {
    if (d.dutyNumber && d.dutyNumber.startsWith('SIC')) {
      const numPart = parseInt(d.dutyNumber.replace('SIC', ''), 10);
      if (!isNaN(numPart) && numPart > highestNum) {
        highestNum = numPart;
      }
    }
  });
  return `SIC${highestNum + 1}`;
};

